"""Phase 2 evaluation: does a fingerprint find captures of the same kind? (EXPERIMENTAL)

    python eval/similarity.py            # analyse data/nullset (cached), evaluate, write results
    python eval/similarity.py --report   # re-evaluate from the cached fingerprints only

Data: the 1,350 labelled null-set captures (data/nullset, generated by eval/nullset.py): noise,
uncoded BPSK/QPSK, K=3 / K=5 / K=7 convolutional codes and 8PSK K=7, at 30 to 384 coded bits.

Protocol, fixed before the first run:
  - fingerprint = src/fingerprint.py on the engine's own result; the generator's labels never enter it
  - split by seed index: even -> reference library, odd -> held-out queries (no capture is both)
  - standardisation fitted on the reference library only
  - a query is correct when its nearest reference capture has the same generator class
Reported against two baselines: picking a reference at random (class frequencies), and knowing
only the engine's verdict (expected accuracy with random tie-breaking among same-verdict captures).

Writes results/similarity_fingerprints.jsonl (cache), results/similarity.json,
results/similarity_report.md, reports/PHASE2_SIMILARITY_REPORT.md (committed copy) and
frontend/public/similarity.json for the console.
"""

import glob
import json
import os
import subprocess
import sys
from collections import Counter, defaultdict
from multiprocessing import Pool

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'src'))
from modem import load_iq                                  # noqa: E402
from pipeline import analyze_iq                            # noqa: E402
from fingerprint import FEATURES, Library, fingerprint     # noqa: E402

DATA = os.path.join(ROOT, 'data', 'nullset')
CACHE = os.path.join(ROOT, 'results', 'similarity_fingerprints.jsonl')


def analyse(path):
    gt = json.load(open(path + '.gt.json'))
    r = analyze_iq(load_iq(path), _all_hypotheses=True)
    name = os.path.basename(path)[:-3]
    return {'file': name, 'class': gt['class'], 'coded_bits': gt['coded_bits'], 'status': r['status'],
            'seed_index': int(name.rsplit('_', 1)[1]), 'fp': fingerprint(r).tolist()}


def build_cache():
    paths = sorted(glob.glob(os.path.join(DATA, '*.iq')))
    with Pool() as pool:
        rows = pool.map(analyse, paths, chunksize=8)
    with open(CACHE, 'w') as f:
        for r in rows:
            f.write(json.dumps(r) + '\n')
    return rows


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (float(c - h), float(c + h))


def evaluate(rows):
    ref = [r for r in rows if r['seed_index'] % 2 == 0]
    qry = [r for r in rows if r['seed_index'] % 2 == 1]
    lib = Library().fit([r['fp'] for r in ref])
    ref_cls = [r['class'] for r in ref]
    hits, p5 = [], []
    for q in qry:
        nn = lib.query(q['fp'], k=5)
        hits.append(ref_cls[nn[0][0]] == q['class'])
        p5.append(sum(ref_cls[i] == q['class'] for i, _ in nn) / 5)
    hits = np.array(hits)

    # Baseline 1: a random reference capture.
    rc = Counter(ref_cls)
    chance = sum(rc[q['class']] / len(ref) for q in qry) / len(qry)
    # Baseline 2: the verdict alone (random tie-break among reference captures with the same verdict).
    by_status = defaultdict(Counter)
    for r in ref:
        by_status[r['status']][r['class']] += 1
    verdict = np.mean([by_status[q['status']][q['class']] / max(1, sum(by_status[q['status']].values())) for q in qry])

    def subset(pred):
        idx = [i for i, q in enumerate(qry) if pred(q)]
        k, n = (int(hits[idx].sum()) if idx else 0), len(idx)
        return {'n': n, 'correct': k, 'top1': k / n if n else None, 'ci95': wilson(k, n)}

    per_class = {c: subset(lambda q, c=c: q['class'] == c) for c in sorted(set(r['class'] for r in rows))}
    per_bits = {str(b): subset(lambda q, b=b: q['coded_bits'] == b) for b in sorted(set(r['coded_bits'] for r in rows))}
    refused = subset(lambda q: q['status'] != 'DECODED' and q['class'] != 'noise')
    # Stricter view: noise queries are the easiest (half the data). Accuracy on signal classes only,
    # against the random baseline for those same queries.
    signal_only = subset(lambda q: q['class'] != 'noise')
    sq = [q for q in qry if q['class'] != 'noise']
    signal_only['baseline_random'] = sum(rc[q['class']] / len(ref) for q in sq) / max(1, len(sq))
    try:
        commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=ROOT, capture_output=True, text=True).stdout.strip() or None
    except OSError:
        commit = None
    k = int(hits.sum())
    return {
        'phase': 'Phase 2 · signal fingerprints and similarity search',
        'status': 'EXPERIMENTAL',
        'dataset': 'data/nullset (synthetic, labelled by the generator)',
        'n_reference': len(ref), 'n_queries': len(qry), 'features': FEATURES,
        'protocol': 'split by seed index (even = reference, odd = held-out query); standardisation fitted on the reference only; '
                    'a query is correct when its nearest reference capture has the same generator class',
        'top1': k / len(qry), 'top1_ci95': wilson(k, len(qry)), 'correct': k,
        'precision_at_5': float(np.mean(p5)),
        'baseline_random': chance, 'baseline_verdict_only': float(verdict),
        'refused_signals': refused, 'signal_classes_only': signal_only, 'per_class': per_class, 'per_coded_bits': per_bits,
        'engine_commit': commit,
        'scope': 'Synthetic benchmark captures only. Not validated on real transmissions; never part of a decision.',
    }


def report_md(s):
    pc = lambda x: '—' if x is None else f'{100 * x:.1f}%'   # noqa: E731
    lines = [
        '# Phase 2 — fingerprint similarity search (EXPERIMENTAL)', '',
        f"Data: {s['dataset']}. {s['n_reference']} reference captures, {s['n_queries']} held-out queries.", '',
        f"Protocol: {s['protocol']}.", '',
        '| Measure | Value |', '|---|---|',
        f"| Top-1 same-class retrieval | **{pc(s['top1'])}** ({s['correct']}/{s['n_queries']}; 95% CI {pc(s['top1_ci95'][0])}–{pc(s['top1_ci95'][1])}) |",
        f"| Precision at 5 | {pc(s['precision_at_5'])} |",
        f"| Baseline: random reference | {pc(s['baseline_random'])} |",
        f"| Baseline: verdict only | {pc(s['baseline_verdict_only'])} |",
        f"| Signal classes only (noise queries excluded) | {pc(s['signal_classes_only']['top1'])} ({s['signal_classes_only']['correct']}/{s['signal_classes_only']['n']}); random {pc(s['signal_classes_only']['baseline_random'])} |",
        f"| Refused captures that carried a signal (not DECODED, not noise) | {pc(s['refused_signals']['top1'])} ({s['refused_signals']['correct']}/{s['refused_signals']['n']}) |",
        '', '## By class', '', '| Class | Queries | Top-1 | 95% CI |', '|---|---|---|---|',
        *[f"| {c} | {v['n']} | {pc(v['top1'])} | {pc(v['ci95'][0])}–{pc(v['ci95'][1])} |" for c, v in s['per_class'].items()],
        '', '## By coded length', '', '| Coded bits | Queries | Top-1 |', '|---|---|---|',
        *[f"| {b} | {v['n']} | {pc(v['top1'])} |" for b, v in s['per_coded_bits'].items()],
        '', f"Fingerprint features ({len(s['features'])}): " + ', '.join(f'`{f}`' for f in s['features']) + '.', '',
        f"Scope: {s['scope']}", '',
        f"Engine commit: `{s['engine_commit']}`. Reproduce: `python eval/nullset.py generate` (deterministic seeds), then `python eval/similarity.py`.", '',
    ]
    return '\n'.join(lines)


def main():
    if '--report' in sys.argv and os.path.exists(CACHE):
        rows = [json.loads(line) for line in open(CACHE)]
    else:
        rows = build_cache()
    s = evaluate(rows)
    json.dump(s, open(os.path.join(ROOT, 'results', 'similarity.json'), 'w'), indent=1)
    open(os.path.join(ROOT, 'results', 'similarity_report.md'), 'w', encoding='utf-8').write(report_md(s))
    # results/ is not in the repository; the committed copy of the report lives in reports/.
    open(os.path.join(ROOT, 'reports', 'PHASE2_SIMILARITY_REPORT.md'), 'w', encoding='utf-8').write(report_md(s))
    json.dump(s, open(os.path.join(ROOT, 'frontend', 'public', 'similarity.json'), 'w'), indent=1)
    print(report_md(s))


if __name__ == '__main__':
    main()
