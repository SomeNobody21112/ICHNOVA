import json
import os
import sys
from collections import Counter, defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'src'))
sys.path.insert(0, HERE)
sys.stdout.reconfigure(encoding='utf-8')

import frontend_mechanism as fm                          # noqa: E402  (verified replication)
import pipeline                                          # noqa: E402  (SHIPPED, unmodified logic)
import space_doppler as sd                               # noqa: E402  (the generator's trajectory)
from analyze import matched_filter_demod                 # noqa: E402
from modem import load_iq, rrc_filter                    # noqa: E402
from pipeline import RX_BETA, analyze_iq                 # noqa: E402

CRITERIA = os.path.join(HERE, 'track_readout_criteria.json')
ROWS = os.path.join('results', 'track_readout_rows.jsonl')
BLOCKS = os.path.join('results', 'track_readout_blocks.jsonl')
DOPPLER = os.path.join('data', 'space_bench', 'doppler')
SEALED_ROWS = os.path.join('results', 'space_doppler_rows.jsonl')
SLIP_TOL = 0.25                                          # of one 2*pi/M ambiguity step (committed)
TIME_VARYING = ('linear', 'pass')


def _front_end(iq, cfo, sps, mod):
    """The symbol stream the engine built for this front end, using the production functions."""
    n = np.arange(len(iq))
    return matched_filter_demod(iq * np.exp(-2j * np.pi * cfo * n), rrc_filter(RX_BETA, sps), sps)


def _true_block_phase(gt, n_samples, cfo_removed, blk, sps, n_blocks):
    """Mean TRUE residual carrier phase over each block, in radians.

    The capture was generated by mixing with the trajectory alone (space_doppler.apply_trajectory),
    so the true instantaneous frequency IS the trajectory. The front end has already removed a
    constant `cfo_removed`, so what the tracker should follow is the difference.
    """
    f = sd.trajectory(gt['trajectory_class'], gt['peak_shift_cyc_per_sample'], n_samples,
                      gt.get('kappa', sd.KAPPA))
    phase = 2 * np.pi * np.cumsum(f - cfo_removed)
    out = []
    for b in range(n_blocks):
        a, z = int(b * blk * sps), int((b + 1) * blk * sps)
        seg = phase[a:min(z, n_samples)]
        out.append(float(np.mean(seg)) if len(seg) else float('nan'))
    return np.array(out)


def _slips(phi, true, m_power):
    """Committed rule: an increment that differs from truth by a non-zero multiple of 2*pi/M."""
    step = 2 * np.pi / m_power
    d = np.diff(phi) - np.diff(true)
    k = np.round(d / step)
    is_slip = (k != 0) & (np.abs(d - k * step) <= SLIP_TOL * step)
    return is_slip, k


def _predicted_slip(true, m_power):
    """From TRUTH alone: unwrap must take the wrong branch when the M-power advance exceeds pi."""
    return np.abs(np.diff(true) * m_power) > np.pi


def run():
    sealed = {json.loads(l)['file']: json.loads(l) for l in open(SEALED_ROWS, encoding='utf-8')}
    rows, blocks = [], []
    files = sorted(f[:-3] for f in os.listdir(DOPPLER) if f.endswith('.iq'))
    for i, name in enumerate(files, 1):
        path = os.path.join(DOPPLER, name + '.iq')
        iq = load_iq(path)
        gt = json.load(open(path + '.gt.json', encoding='utf-8'))
        prev = sealed.get(name, {})
        r = analyze_iq(iq)                                # SHIPPED ENGINE, no trace passed
        sc = r.get('stream_code') or {}
        claim = sc.get('accepted_hypothesis') if sc.get('accepted') else None

        # which front end produced the claim, and was it the tracked variant?
        meta, cands = fm._front_candidates(iq)
        passing = [c for c in cands if c['passed']]
        src, tracking, cfo, sps, mod, mapped = 'reference', None, None, None, None, None
        if claim is not None and claim['front'] < len(passing):
            f = passing[claim['front']]
            mapped = (abs(f['cfo'] - claim['cfo']) < 1e-12 and f['sps'] == claim['sps']
                      and f['mod'] == claim['modulation'])
            if mapped:
                src, tracking = 'claim', f['tracking']
                cfo, sps, mod = f['cfo'], f['sps'], f['mod']
        if cfo is None:                                   # refused, or mapping failed: use the
            cfo = float(np.mean(sd.trajectory(                        # TRUE front end as reference
                gt['trajectory_class'], gt['peak_shift_cyc_per_sample'], len(iq),
                gt.get('kappa', sd.KAPPA))))
            sps, mod = int(gt['sps']), gt['modulation']

        y = _front_end(iq, cfo, sps, mod)
        trace = {}
        tracked = pipeline._track_phase(y, mod, _trace=trace)
        row = {'file': name, 'trajectory': gt['trajectory_class'],
               'severity': gt['severity'], 'peak': gt['peak_shift_cyc_per_sample'],
               'length': (gt.get('params') or {}).get('length'), 'esn0_db': gt['esn0_db'],
               'true_sps': gt['sps'], 'n_symbols_true': gt['n_symbols'],
               'outcome': prev.get('outcome'), 'status': r['status'], 'final_code': r['code'],
               'phase_tracked_front_ends': r['diagnostics']['phase_tracked_front_ends'],
               'front_source': src, 'claim_front': None if claim is None else claim['front'],
               'front_mapped': mapped, 'claim_tracking': tracking,
               'cfo_removed': cfo, 'sps': sps, 'mod': mod, 'n_symbols_front': int(len(y)),
               'tracker_ran': tracked is not None}
        if tracked is None:
            row.update({'block': None, 'coherence': None, 'n_blocks': 0, 'n_slips': None,
                        'n_predicted_slips': None, 'max_abs_err_rad': None,
                        'final_err_rad': None, 'why_not': 'below TRACK_MIN_SYMBOLS'})
            rows.append(row)
            continue
        phi = np.array(trace['phase'])
        true = _true_block_phase(gt, len(iq), cfo, trace['block'], sps, len(phi))
        ok = np.isfinite(true)
        phi_r, true_r = phi[ok] - phi[ok][0], true[ok] - true[ok][0]
        err = phi_r - true_r
        is_slip, k = _slips(phi[ok], true[ok], trace['m_power'])
        pred = _predicted_slip(true[ok], trace['m_power'])
        row.update({'block': trace['block'], 'coherence': trace['coherence'],
                    'coherence_by_block': {str(a): b for a, b in
                                           trace.get('coherence_by_block', {}).items()},
                    'n_blocks': int(len(phi_r)), 'n_slips': int(is_slip.sum()),
                    'slip_orders': sorted({int(v) for v in k[is_slip]}),
                    'n_predicted_slips': int(pred.sum()),
                    'max_abs_err_rad': float(np.max(np.abs(err))),
                    'final_err_rad': float(err[-1]),
                    'max_true_incr_rad': (float(np.max(np.abs(np.diff(true_r))))
                                          if len(true_r) > 1 else 0.0),
                    'why_not': None})
        rows.append(row)
        if gt['trajectory_class'] in TIME_VARYING:
            for b in range(len(phi_r)):
                blocks.append({'file': name, 'block_index': b, 'tracker_rad': float(phi_r[b]),
                               'true_rad': float(true_r[b]), 'err_rad': float(err[b]),
                               'slip': bool(is_slip[b - 1]) if b else False})
        if i % 48 == 0:
            print(f'  {i}/{len(files)}')

    os.makedirs('results', exist_ok=True)
    with open(ROWS, 'w', encoding='utf-8') as f:
        for r in rows:
            f.write(json.dumps(r) + '\n')
    with open(BLOCKS, 'w', encoding='utf-8') as f:
        for b in blocks:
            f.write(json.dumps(b) + '\n')
    # verdicts must be unchanged: the sealed run recorded status per capture, with no trace anywhere
    bad = [r['file'] for r in rows
           if sealed.get(r['file'], {}).get('status') not in (None, r['status'])]
    print(f'\n{len(rows)} captures, {len(blocks)} block samples -> {ROWS}, {BLOCKS}')
    print(f'tracker ran on {sum(1 for r in rows if r["tracker_ran"])}/{len(rows)}')
    print('VERDICTS UNCHANGED vs the sealed SPACE-DOPPLER run' if not bad
          else f'STOP: verdicts differ on {bad[:5]}')


def report():
    rows = [json.loads(l) for l in open(ROWS, encoding='utf-8')]
    print(f'\nSPACE-TRACK-READOUT-01 — {len(rows)} sealed Doppler captures; criteria sha256 '
          f'{hashlib.sha256(open(CRITERIA, "rb").read()).hexdigest()[:16]}…\n')
    ran = [r for r in rows if r['tracker_ran']]
    print(f'TRACKER RAN on {len(ran)}/{len(rows)}; block length chosen: '
          f'{dict(Counter(r["block"] for r in ran))}')
    print(f'  (it returns None below TRACK_MIN_SYMBOLS = {pipeline.TRACK_MIN_SYMBOLS} symbols)')

    print('\nACCURACY vs THE KNOWN TRAJECTORY (radians, referenced to block 0)')
    print('  trajectory   n   blocks  max|err| med   final|err| med  slips>0  predicted-slips>0')
    for cls in ('zero', 'static', 'linear', 'pass'):
        xs = [r for r in ran if r['trajectory'] == cls]
        if not xs:
            continue
        me = np.median([r['max_abs_err_rad'] for r in xs])
        fe = np.median([abs(r['final_err_rad']) for r in xs])
        print(f'  {cls:10}{len(xs):5}{np.median([r["n_blocks"] for r in xs]):8.0f}'
              f'{me:14.3f}{fe:15.3f}{sum(1 for r in xs if r["n_slips"]):9}'
              f'{sum(1 for r in xs if r["n_predicted_slips"]):19}')

    print('\nH3 — SLIPS vs OUTCOME (time-varying captures only)')
    tv = [r for r in ran if r['trajectory'] in TIME_VARYING]
    for oc in ('FALSE_DECODE', 'DECODED_CORRECT', 'REFUSED'):
        xs = [r for r in tv if r['outcome'] == oc]
        if not xs:
            continue
        print(f'  {oc:16} n={len(xs):3}  captures with >=1 slip: '
              f'{sum(1 for r in xs if r["n_slips"]):3}  median max|err| '
              f'{np.median([r["max_abs_err_rad"] for r in xs]):.3f} rad')

    print('\nDID THE CLAIM COME FROM A TRACKED FRONT END?  (this is what H3 needs)')
    claims = [r for r in rows if r['front_source'] == 'claim']
    n_claims = sum(1 for r in rows if r['claim_front'] is not None)
    print(f'  claims mapped to a front end: {len(claims)}/{n_claims}')
    print(f'  tracking variant of the claim front end: '
          f'{dict(Counter(r["claim_tracking"] for r in claims))}')
    fd = [r for r in claims if r['outcome'] == 'FALSE_DECODE']
    print(f'  of the {len(fd)} FALSE_DECODE captures with a mapped claim: '
          f'{dict(Counter(r["claim_tracking"] for r in fd))}')
    print(f'  FALSE_DECODE captures with NO tracked front end anywhere: '
          f'{sum(1 for r in rows if r["outcome"] == "FALSE_DECODE" and r["phase_tracked_front_ends"] == 0)}'
          f' of {sum(1 for r in rows if r["outcome"] == "FALSE_DECODE")}')

    print('\nSEVERITY (is the error systematic?)')
    by = defaultdict(list)
    for r in ran:
        if r['trajectory'] in TIME_VARYING:
            by[r['severity']].append(r)
    for s in sorted(by):
        xs = by[s]
        print(f'  severity {s:<5} n={len(xs):3} median max|err| '
              f'{np.median([r["max_abs_err_rad"] for r in xs]):7.3f} rad  median max true '
              f'increment {np.median([r["max_true_incr_rad"] for r in xs]):6.3f} rad  slips '
              f'{sum(r["n_slips"] for r in xs)}')


def demo():
    """Self-check: the slip rule fires on a synthetic 2*pi/M step and not on clean tracking."""
    m = 2
    true = np.array([0.0, 0.5, 1.0, 1.5, 2.0])
    clean = true + np.array([0.0, 0.01, -0.01, 0.02, 0.0])          # small noise, no slip
    assert not _slips(clean, true, m)[0].any()
    slipped = true.copy()
    slipped[2:] += 2 * np.pi / m                                    # one persistent step
    is_slip, k = _slips(slipped, true, m)
    assert is_slip.sum() == 1 and int(k[is_slip][0]) == 1, (is_slip, k)
    # and the truth-side predictor fires exactly when the M-power advance exceeds pi
    assert not _predicted_slip(np.array([0.0, np.pi / 2 - 0.01]), m)[0]
    assert _predicted_slip(np.array([0.0, np.pi / 2 + 0.01]), m)[0]
    print('demo: slip rule and truth-side predictor self-checks pass')


if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'demo'
    os.chdir(ROOT)
    {'run': run, 'report': report, 'demo': demo}[cmd]()
