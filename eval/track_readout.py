"""SPACE-TRACK-READOUT-01 — what does the shipped `_track_phase` estimate on a moving carrier?

Criteria: `eval/track_readout_criteria.json`, committed before this file existed.

The tracker estimates a piecewise-constant carrier PHASE: per block of `blk` symbols it takes
angle(mean(y**M)), unwraps that across blocks, divides by M, and de-rotates the block by the result.
`np.unwrap` assumes the block-to-block change is below pi, so when the true M-power advance per block
exceeds pi the recovered phase acquires a step of 2*pi/M that persists — which is the shape of the
measured Doppler failure (wrong payload beneath a TRUE structure). That is hypothesis H3, and this
harness measures whether it actually happens.

The only production change is the write-only `_trace` dict on `_track_phase`; the engine never passes
it and the returned stream is identical with or without it. Everything else is read-only.

    python eval/track_readout.py run
    python eval/track_readout.py report
"""

